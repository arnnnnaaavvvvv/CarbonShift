def test_golden_case_5_cross_region_transfer():
    """Golden Case 5: Cross-region 50 GB transfer -> exact 280.0 gCO2e."""
    e_xfer, c_xfer, cost = compute_transfer_footprint(
        data_size_gb=50.0,
        is_cross_region=True,
        egress_cost_per_gb=0.02,
        network_kwh_per_gb=0.014,
        net_intensity_gco2e_per_kwh=400.0,
    )
    assert math.isclose(e_xfer, 0.70, rel_tol=1e-12)
    assert math.isclose(c_xfer, 280.0, rel_tol=1e-12)
    assert math.isclose(cost, 1.00, rel_tol=1e-12)


def test_golden_case_6_slot_boundary_invariants():
    """Golden Case 6: Exact boundary hits and zero-length jobs."""
    # Starts exactly on boundary
    w_start_boundary_0 = compute_slot_overlap_fraction(3600.0, 7200.0, 0.0, 3600.0)
    w_start_boundary_1 = compute_slot_overlap_fraction(3600.0, 7200.0, 3600.0, 7200.0)
    assert w_start_boundary_0 == 0.0
    assert w_start_boundary_1 == 1.0

    # Ends exactly on boundary
    w_end_boundary_0 = compute_slot_overlap_fraction(0.0, 3600.0, 0.0, 3600.0)
    w_end_boundary_1 = compute_slot_overlap_fraction(0.0, 3600.0, 3600.0, 7200.0)
    assert w_end_boundary_0 == 1.0
    assert w_end_boundary_1 == 0.0

    # Zero-length job
    w_zero = compute_slot_overlap_fraction(1800.0, 1800.0, 0.0, 3600.0)
    assert w_zero == 0.0
