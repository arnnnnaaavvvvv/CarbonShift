"""Hand-computed golden tests pre-calculated in docs/MATH.md §3.2.

These values were worked out by hand on paper and verified against analytical formulas.
None of these numbers were generated by the code under test.
"""

import math
import pytest
from carbonshift.core.math import (
    compute_server_power_kw,
    compute_slot_overlap_fraction,
    compute_slot_energy_kwh,
    compute_slot_carbon_gco2e,
    compute_transfer_footprint,
    precise_fsum,
)


def test_golden_case_1_one_slot_job():
    """Golden Case 1: 1-slot job, u=0.5, PUE=1.0, I=200 -> exact 50.31433133020796 gCO2e."""
    p_kw = compute_server_power_kw(0.5, p_idle_kw=0.100, p_max_kw=0.500, curvature_r=1.4)
    w = compute_slot_overlap_fraction(0.0, 3600.0, 0.0, 3600.0)
    e = compute_slot_energy_kwh(p_kw, 1.0, 1.0, w)
    c = compute_slot_carbon_gco2e(e, 200.0)
    assert math.isclose(c, 50.31433133020796, rel_tol=1e-12)


def test_golden_case_2_three_slot_job_variable_intensity():
    """Golden Case 2: 3-slot job, variable intensities [300, 150, 100] -> exact 138.36441115807189 gCO2e."""
    p_kw = compute_server_power_kw(0.5, p_idle_kw=0.100, p_max_kw=0.500, curvature_r=1.4)
    intensities = [300.0, 150.0, 100.0]
    carbons = []
    for idx, intensity in enumerate(intensities):
        s_start, s_end = idx * 3600.0, (idx + 1) * 3600.0
        w = compute_slot_overlap_fraction(0.0, 10800.0, s_start, s_end)
        e = compute_slot_energy_kwh(p_kw, 1.0, 1.0, w)
        carbons.append(compute_slot_carbon_gco2e(e, intensity))
    total_c = precise_fsum(carbons)
    assert math.isclose(total_c, 138.36441115807189, rel_tol=1e-12)


def test_golden_case_3_partial_slot_edge_overlap():
    """Golden Case 3: Partial overlap [1800s, 7200s] across 2 slots -> exact 75.47149699531194 gCO2e."""
    p_kw = compute_server_power_kw(0.5, p_idle_kw=0.100, p_max_kw=0.500, curvature_r=1.4)
    # Slot 0 [0, 3600], I=300
    w0 = compute_slot_overlap_fraction(1800.0, 7200.0, 0.0, 3600.0)
    e0 = compute_slot_energy_kwh(p_kw, 1.0, 1.0, w0)
    c0 = compute_slot_carbon_gco2e(e0, 300.0)

    # Slot 1 [3600, 7200], I=150
    w1 = compute_slot_overlap_fraction(1800.0, 7200.0, 3600.0, 7200.0)
    e1 = compute_slot_energy_kwh(p_kw, 1.0, 1.0, w1)
    c1 = compute_slot_carbon_gco2e(e1, 150.0)

    total_c = precise_fsum([c0, c1])
    assert math.isclose(total_c, 75.47149699531194, rel_tol=1e-12)


